"""Site-scale DEM previews for the experimental 3D terrain view (Phase 4 Task 6).

Serves the committed 128x128 average-pooled height grids in
``data/scientific/site_dems/`` (generated by
``backend/scripts/export_site_dem_previews.py`` from the PGDA 5 m/pix site
models). The endpoint copies the committed evidence; it computes nothing, so
what the 3D view shows can always be traced to the source raster via the
recorded file name and SHA-256.

The payload keeps the LOLA absolute heights (metres above the 1737.4 km
reference sphere) plus the pooled height of the site cell; subtracting the
latter is the viewer's business, not the data's. Geometry only.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from app.core.errors import DataUnavailableError, UnknownSiteError
from app.core.settings import Settings, get_settings, _resolve
from app.services.sites import get_site_repository

SCHEMA = "lunanav.terrain_dem.v1"
GRID = 128
MAX_ABSOLUTE_HEIGHT_M = 10_000.0  # LOLA south-polar heights stay far inside this

NOTES = (
    "Experimental: heights are average-pooled to 125 m cells from the 5 m/pix "
    "PGDA site model, so this preview resolves hills and rims, not boulders or "
    "the landing ellipse.",
    "Heights are metres above the 1737.4 km LOLA reference sphere; the 3D view "
    "renders them relative to the pooled site-cell height and may exaggerate "
    "them for readability, always labelled.",
    "The 2D terrain horizon profile (GET /api/terrain-horizon) and its numbers "
    "remain the source of truth for visibility; this mesh is display only.",
)


def _document(site_id: str, settings: Settings) -> dict:
    directory = (settings.raw.get("datasets") or {}).get("site_dem_dir")
    if not directory:
        raise DataUnavailableError(
            "No site_dem_dir is configured, so no site DEM preview can be served.",
            details={"code": "DEM_UNAVAILABLE"},
        )
    path = _resolve(directory) / f"{site_id}.json"
    if not path.exists():
        raise DataUnavailableError(
            f"No committed site DEM preview for '{site_id}' "
            f"(generate one with backend/scripts/export_site_dem_previews.py).",
            details={"code": "DEM_UNAVAILABLE"},
        )
    try:
        document = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        raise DataUnavailableError(
            f"Site DEM preview {path.name} is not valid JSON: {exc}",
            details={"code": "DEM_UNAVAILABLE"},
        ) from exc
    if document.get("schema") != "lunanav.site_dem_preview.v1":
        raise DataUnavailableError(
            f"Site DEM preview {path.name} has schema {document.get('schema')!r}, "
            "expected lunanav.site_dem_preview.v1",
            details={"code": "DEM_UNAVAILABLE"},
        )
    return document


def terrain_dem_response(*, site_id: str, settings: Settings | None = None) -> dict:
    """One candidate's pooled DEM grid for the (feature-flagged) 3D view."""
    settings = settings or get_settings()
    site = get_site_repository().get(site_id)
    if site.id != site_id:
        raise UnknownSiteError(f"unknown site '{site_id}'")
    document = _document(site_id, settings)
    heights = np.asarray(document["heights_m"], dtype=float)
    if heights.shape != (GRID, GRID):
        raise DataUnavailableError(
            f"Site DEM preview {site_id} has grid {heights.shape}, expected ({GRID}, {GRID})",
            details={"code": "DEM_UNAVAILABLE"},
        )
    if not np.isfinite(heights).all() or float(np.abs(heights).max()) > MAX_ABSOLUTE_HEIGHT_M:
        raise DataUnavailableError(
            f"Site DEM preview {site_id} has non-finite or implausible heights",
            details={"code": "DEM_UNAVAILABLE"},
        )
    cell_m = float(document["cell_m"])
    if not 100.0 <= cell_m <= 200.0:
        raise DataUnavailableError(
            f"Site DEM preview {site_id} declares cell_m={cell_m}, expected ~125 m pooling",
            details={"code": "DEM_UNAVAILABLE"},
        )
    site_height = float(document["site_height_m"])
    return {
        "schema": SCHEMA,
        "site": {
            "site_id": site.id,
            "name": site.name,
            "latitude_deg": site.latitude_deg,
            "longitude_deg": site.longitude_deg,
        },
        "grid": {
            "size": GRID,
            "cell_m": cell_m,
            "extent_m": document["extent_m"],
            "bounds_m": document["bounds_m"],
            "site_cell": document["site_cell"],
            "nodata_fill_cells": document.get("nodata_fill_cells", 0),
        },
        "heights_m": document["heights_m"],
        "site_height_m": site_height,
        "height_convention": document["height_convention"],
        "crs": document["crs"],
        "source": document["source"],
        "provenance": "scientific_sourced",
        "notes": NOTES,
    }
