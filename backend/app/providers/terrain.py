"""Terrain horizon providers.

- ``SyntheticHorizonProvider`` (Demo Mode): reads clearly-labelled SYNTHETIC
  skyline profiles from ``data/demo/horizon_masks.json``. For coordinates with
  no synthetic profile it falls back to a flat horizon and labels the result
  ``geometric_only`` so the UI can say "terrain not applied".
- ``LolaHorizonMaskProvider`` (Scientific Mode): reads horizon masks derived
  from LOLA DEMs (see ``app/services/horizon.py::build_horizon_mask_from_dem``
  and ``scripts/build_horizon_mask.py``). Missing mask -> DataUnavailableError.
- ``FlatHorizonProvider``: geometric horizon only; useful as an explicit choice.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

import numpy as np

from app.core.coords import angular_distance_deg
from app.core.errors import DataUnavailableError
from app.core.settings import rel
from app.models.schemas import EffectsIncluded, ProvenanceLevel

from .base import HorizonMask, LunarTerrainProvider, flat_mask, make_info

MATCH_TOLERANCE_KM = 0.25


def _load_mask_file(path: Path, provenance: ProvenanceLevel) -> dict:
    raw = json.loads(path.read_text())
    return {
        "site_id": raw.get("site_id"),
        "lat": raw.get("latitude_deg"),
        "lon": raw.get("longitude_deg"),
        "mask": HorizonMask(
            np.asarray(raw["azimuth_deg"], float),
            np.asarray(raw["elevation_deg"], float),
            source=raw.get("source", str(path)),
            provenance=provenance,
            metadata={k: v for k, v in raw.items() if k not in ("azimuth_deg", "elevation_deg")},
        ),
    }


class SyntheticHorizonProvider(LunarTerrainProvider):
    id = "synthetic_horizon"

    def __init__(self, path: Path):
        self.path = Path(path)
        self._masks: dict[str, HorizonMask] = {}
        if self.path.exists():
            raw = json.loads(self.path.read_text())
            for site_id, prof in raw["profiles"].items():
                self._masks[site_id] = HorizonMask(
                    np.asarray(prof["azimuth_deg"], float),
                    np.asarray(prof["elevation_deg"], float),
                    source="SYNTHETIC demo skyline (data/demo/horizon_masks.json) - not real terrain",
                    provenance=ProvenanceLevel.synthetic,
                )

    def info(self):
        return make_info(
            id=self.id,
            kind="terrain",
            name="Synthetic demo horizon profiles",
            provenance=ProvenanceLevel.synthetic,
            source="Generated by backend/scripts/generate_demo_data.py (seeded random skyline)",
            description=(
                "Invented skyline profiles that exercise the terrain-obstruction logic. "
                "They do NOT represent real lunar topography."
            ),
            effects=EffectsIncluded(
                terrain_topography=False,
                notes=["Skyline shapes are synthetic.", "Custom coordinates use a flat horizon."],
            ),
            available=True,
        )

    def horizon_mask(self, lat_deg, lon_deg, site_id: Optional[str] = None) -> HorizonMask:
        if site_id and site_id in self._masks:
            return self._masks[site_id]
        return flat_mask(
            "No terrain profile for these coordinates: flat geometric horizon used",
            ProvenanceLevel.geometric_only,
        )


class LolaHorizonMaskProvider(LunarTerrainProvider):
    id = "lola_horizon_mask"

    def __init__(self, directory: Path):
        self.directory = Path(directory)
        self._entries: list[dict] = []
        if self.directory.exists():
            for p in sorted(self.directory.glob("*.json")):
                self._entries.append(_load_mask_file(p, ProvenanceLevel.scientific_sourced))

    def info(self):
        available = bool(self._entries)
        return make_info(
            id=self.id,
            kind="terrain",
            name="LOLA-derived horizon masks",
            provenance=ProvenanceLevel.scientific_sourced,
            source="LRO LOLA polar DEMs (PDS Geosciences Node) processed by scripts/build_horizon_mask.py",
            description="Skyline elevation vs azimuth computed by ray-marching a LOLA DEM with lunar curvature.",
            effects=EffectsIncluded(
                terrain_topography=True,
                lunar_curvature_in_horizon=True,
                notes=["Accuracy limited by DEM resolution and ray-march range."],
            ),
            available=available,
            unavailable_reason=None
            if available
            else f"No LOLA horizon masks found in {rel(self.directory)}. See docs/ADAPTATION_GUIDE.md.",
        )

    def horizon_mask(self, lat_deg, lon_deg, site_id: Optional[str] = None) -> HorizonMask:
        if not self._entries:
            raise DataUnavailableError(self.info().unavailable_reason)
        for e in self._entries:
            if site_id and e["site_id"] == site_id:
                return e["mask"]
        for e in self._entries:
            if e["lat"] is None:
                continue
            d_km = np.radians(angular_distance_deg(lat_deg, lon_deg, e["lat"], e["lon"])) * 1737.4
            if d_km <= MATCH_TOLERANCE_KM:
                return e["mask"]
        raise DataUnavailableError(
            f"No LOLA horizon mask within {MATCH_TOLERANCE_KM} km of ({lat_deg:.4f}, {lon_deg:.4f}).",
            details={"site_id": site_id},
        )


class FlatHorizonProvider(LunarTerrainProvider):
    id = "flat"

    def info(self):
        return make_info(
            id=self.id,
            kind="terrain",
            name="Flat geometric horizon",
            provenance=ProvenanceLevel.geometric_only,
            source="None (spherical Moon)",
            description="No topography. Visibility equals geometric elevation > 0.",
            available=True,
        )

    def horizon_mask(self, lat_deg, lon_deg, site_id=None):
        return flat_mask("Flat geometric horizon (no terrain)", ProvenanceLevel.geometric_only)
